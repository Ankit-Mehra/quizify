"""
Google Forms Exporter - Export quizzes to Google Forms.

This module creates Google Forms from Quizify quizzes using the Google Forms API.
It requires OAuth2 authentication with the user's Google account.

The exported form:
- Has quiz mode enabled with auto-grading
- Maps MCQ and True/False to Radio choice questions
- Maps Fill-in-the-blank to short answer questions
- Skips Matching questions (not supported by Forms API)

Reference: https://developers.google.com/forms/api/reference/rest
"""

from typing import TYPE_CHECKING, Any, Dict, List, Optional

from googleapiclient.discovery import build
from googleapiclient.errors import HttpError

from schemas.export import ExportResult
from services.exporters.base import BaseExporter, ExportError, GoogleConnectionRequiredError
from services.logger import app_logger as logger

if TYPE_CHECKING:
    from schemas.export import (
        ExportOptions,
        ExportQuestionFillBlank,
        ExportQuestionMCQ,
        ExportQuestionTrueFalse,
        QuizExportData,
    )


# Google Forms API constants
FORMS_API_VERSION = "v1"
FORMS_DISCOVERY_DOC = "https://forms.googleapis.com/$discovery/rest?version=v1"


class GoogleFormsExporter(BaseExporter):
    """
    Export quizzes to Google Forms.
    
    Creates a new Google Form with:
    - Quiz mode enabled (auto-grading)
    - Questions with correct answers configured
    - Point values for each question
    
    Supported question types:
    - Multiple Choice → Radio (choiceQuestion)
    - True/False → Radio with True/False options
    - Fill in the Blank → Short Answer (textQuestion)
    
    Unsupported:
    - Matching (skipped with warning)
    
    Note: This exporter requires the user to have connected their Google account.
    Credentials are fetched from the database using the user_id.
    """
    
    FORMAT_NAME = "google_forms"
    CONTENT_TYPE = "application/json"  # Returns JSON with URLs, not a file
    FILE_EXTENSION = ""  # No file download
    
    # Default point value per question
    DEFAULT_POINT_VALUE = 1
    
    def __init__(self, user_id: Optional[str] = None, user_token: Optional[str] = None):
        """
        Initialize the Google Forms exporter.
        
        Args:
            user_id: User ID for fetching Google OAuth credentials
            user_token: JWT token for authenticated operations (optional, for API
                       consistency with other exporters like ShareLinkExporter)
        """
        self._service = None
        self._credentials = None
        self._user_id = user_id
        self._user_token = user_token  # Reserved for future use
    
    async def export(
        self,
        quiz_data: "QuizExportData",
        options: "ExportOptions"
    ) -> ExportResult:
        """
        Export quiz to Google Forms.
        
        Args:
            quiz_data: Quiz data with questions
            options: Export options (include_answer_key affects grading setup)
            
        Returns:
            ExportResult with form URLs (form_url, edit_url, form_id)
            
        Raises:
            ExportError: If export fails or user is not connected to Google
        """
        # Get credentials from the database
        from services.google_auth_service import get_google_credentials
        
        if not self._user_id:
            raise ExportError(
                "User ID required for Google Forms export",
                self.FORMAT_NAME
            )
        
        credentials = await get_google_credentials(self._user_id)
        
        if not credentials:
            raise GoogleConnectionRequiredError()
        
        try:
            # Build the Forms API service
            service = build(
                "forms",
                FORMS_API_VERSION,
                credentials=credentials,
                discoveryServiceUrl=FORMS_DISCOVERY_DOC,
                static_discovery=False
            )
            
            # Step 1: Create the form with title and description
            # Use default description if none provided
            description = quiz_data.description or "Quiz generated by Quizify"
            form_id = await self._create_form(
                service, 
                quiz_data.title, 
                description
            )
            logger.info(f"Created Google Form: {form_id}")
            
            # Step 2: Enable quiz mode
            await self._enable_quiz_mode(service, form_id)
            logger.info(f"Enabled quiz mode for form: {form_id}")
            
            # Step 3: Add questions
            skipped_questions = await self._add_questions(
                service, form_id, quiz_data.questions, options
            )
            
            if skipped_questions:
                logger.warning(
                    f"Skipped {len(skipped_questions)} unsupported questions: "
                    f"{skipped_questions}"
                )
            
            # Get form URLs (wrap in thread to avoid blocking)
            import asyncio
            
            def get_form():
                return service.forms().get(formId=form_id).execute()
            
            form = await asyncio.to_thread(get_form)
            responder_uri = form.get(
                "responderUri", 
                f"https://docs.google.com/forms/d/e/{form_id}/viewform"
            )
            edit_uri = f"https://docs.google.com/forms/d/{form_id}/edit"
            
            # Calculate questions exported and skipped
            questions_exported = len(quiz_data.questions) - len(skipped_questions)
            
            # Build warnings list
            warnings = []
            if skipped_questions:
                for q_type in skipped_questions:
                    warnings.append(
                        f"Question type '{q_type}' is not supported by Google Forms"
                    )
            
            logger.info(
                f"Exported quiz '{quiz_data.title}' to Google Forms: {form_id}"
            )
            
            # Return result with URLs and metadata
            return ExportResult(
                content=b"",  # No file content
                content_type=self.CONTENT_TYPE,
                filename=None,
                share_url=responder_uri,
                form_url=responder_uri,
                edit_url=edit_uri,
                form_id=form_id,
                questions_exported=questions_exported,
                questions_skipped=len(skipped_questions),
                warnings=warnings if warnings else None
            )
            
        except HttpError as e:
            error_reason = e.reason if hasattr(e, 'reason') else str(e)
            logger.error(f"Google Forms API error: {error_reason}")
            raise ExportError(
                f"Google Forms API error: {error_reason}",
                self.FORMAT_NAME
            )
        except Exception as e:
            logger.error(f"Google Forms export failed: {str(e)}", exc_info=True)
            raise ExportError(f"Export failed: {str(e)}", self.FORMAT_NAME)
    
    async def _create_form(
        self, 
        service, 
        title: str, 
        description: Optional[str] = None
    ) -> str:
        """
        Create a new Google Form.
        
        Note: Google Forms API only allows setting title during creation.
        Description must be added via batchUpdate after form is created.
        
        Args:
            service: Google Forms API service
            title: Form title
            description: Optional form description (added via batchUpdate)
            
        Returns:
            Form ID
        """
        import asyncio
        
        # Google Forms API only allows title during creation
        form_body = {
            "info": {
                "title": title,
            }
        }
        
        def create():
            return service.forms().create(body=form_body).execute()
        
        result = await asyncio.to_thread(create)
        form_id = result["formId"]
        
        # Add description via batchUpdate if provided
        if description:
            await self._set_form_description(service, form_id, description)
        
        return form_id

    async def _set_form_description(
        self,
        service,
        form_id: str,
        description: str
    ) -> None:
        """
        Set form description via batchUpdate.
        
        Args:
            service: Google Forms API service
            form_id: Google Form ID
            description: Form description
            
        Raises:
            HttpError: If the API call fails
        """
        import asyncio
        
        update_request = {
            "requests": [
                {
                    "updateFormInfo": {
                        "info": {
                            "description": description
                        },
                        "updateMask": "description"
                    }
                }
            ]
        }
        
        def update():
            return service.forms().batchUpdate(
                formId=form_id,
                body=update_request
            ).execute()
        
        try:
            await asyncio.to_thread(update)
        except HttpError as e:
            logger.error(f"Failed to set form description for form_id={form_id}: {e}")
            raise
    
    async def _enable_quiz_mode(self, service, form_id: str) -> None:
        """
        Enable quiz mode on the form.
        
        Args:
            service: Google Forms API service
            form_id: Google Form ID
        """
        import asyncio
        
        update_request = {
            "requests": [
                {
                    "updateSettings": {
                        "settings": {
                            "quizSettings": {
                                "isQuiz": True
                            }
                        },
                        "updateMask": "quizSettings.isQuiz"
                    }
                }
            ]
        }
        
        def update():
            return service.forms().batchUpdate(
                formId=form_id,
                body=update_request
            ).execute()
        
        try:
            await asyncio.to_thread(update)
        except HttpError as e:
            logger.error(f"Failed to enable quiz mode for form_id={form_id}: {e}")
            raise
    
    async def _add_questions(
        self,
        service,
        form_id: str,
        questions: List,
        options: "ExportOptions"
    ) -> List[str]:
        """
        Add questions to the form.
        
        Args:
            service: Google Forms API service
            form_id: Google Form ID
            questions: List of ExportQuestion objects
            options: Export options
            
        Returns:
            List of skipped question types
        """
        import asyncio
        
        requests = []
        skipped = []
        form_index = 0  # Track actual form index (excludes skipped questions)
        
        for idx, question in enumerate(questions):
            question_type = question.type
            
            if question_type == "multiple_choice":
                item = self._build_mcq_item(question, form_index, options)
                requests.append({"createItem": item})
                form_index += 1
                
            elif question_type == "true_false":
                item = self._build_true_false_item(question, form_index, options)
                requests.append({"createItem": item})
                form_index += 1
                
            elif question_type == "fill_blank":
                item = self._build_fill_blank_item(question, form_index, options)
                requests.append({"createItem": item})
                form_index += 1
                
            elif question_type == "matching":
                # Matching questions not supported by Google Forms API
                skipped.append(f"Q{idx + 1}: matching")
                logger.warning(
                    f"Skipping matching question at index {idx} - not supported"
                )
                # Don't increment form_index - question is skipped
                
            else:
                skipped.append(f"Q{idx + 1}: {question_type}")
                logger.warning(f"Unknown question type: {question_type}")
                # Don't increment form_index - question is skipped
        
        if requests:
            batch_request = {"requests": requests}
            
            def batch_update():
                return service.forms().batchUpdate(
                    formId=form_id,
                    body=batch_request
                ).execute()
            
            await asyncio.to_thread(batch_update)
        
        return skipped
    
    def _build_mcq_item(
        self,
        question: "ExportQuestionMCQ",
        index: int,
        options: "ExportOptions"
    ) -> Dict[str, Any]:
        """Build a multiple choice question item for Google Forms."""
        
        # Build options list
        form_options = [{"value": opt} for opt in question.options]
        
        # Find correct answer index
        correct_idx = self._find_correct_option_index(
            question.options, question.correct_answer
        )
        
        item = {
            "item": {
                "title": question.question,
                "questionItem": {
                    "question": {
                        "required": True,
                        "choiceQuestion": {
                            "type": "RADIO",
                            "options": form_options,
                            "shuffle": False
                        }
                    }
                }
            },
            "location": {"index": index}
        }
        
        # Add grading if answer key is included
        if options.include_answer_key:
            grading = {
                "pointValue": self.DEFAULT_POINT_VALUE,
                "correctAnswers": {
                    "answers": [{"value": question.options[correct_idx]}]
                }
            }
            
            # Add feedback if explanations are included
            if options.include_explanations:
                explanation = getattr(question, 'explanation', None)
                distractors = getattr(question, 'distractor_explanations', None)
                
                feedback_text = ""
                if explanation:
                    feedback_text += f"{explanation}\n\n"
                
                if distractors and isinstance(distractors, dict):
                    feedback_text += "Why other options are incorrect:\n"
                    for opt, reason in distractors.items():
                        feedback_text += f"• {opt}: {reason}\n"
                
                if feedback_text:
                    feedback_text = feedback_text.strip()
                    grading["whenRight"] = {"text": feedback_text}
                    grading["whenWrong"] = {"text": feedback_text}
            
            item["item"]["questionItem"]["question"]["grading"] = grading
        
        return item
    
    def _build_true_false_item(
        self,
        question: "ExportQuestionTrueFalse",
        index: int,
        options: "ExportOptions"
    ) -> Dict[str, Any]:
        """Build a true/false question item for Google Forms."""
        
        # True/False as radio options
        form_options = [
            {"value": "True"},
            {"value": "False"}
        ]
        
        correct_value = "True" if question.correct_answer else "False"
        
        item = {
            "item": {
                "title": question.question,
                "questionItem": {
                    "question": {
                        "required": True,
                        "choiceQuestion": {
                            "type": "RADIO",
                            "options": form_options,
                            "shuffle": False
                        }
                    }
                }
            },
            "location": {"index": index}
        }
        
        # Add grading if answer key is included
        if options.include_answer_key:
            grading = {
                "pointValue": self.DEFAULT_POINT_VALUE,
                "correctAnswers": {
                    "answers": [{"value": correct_value}]
                }
            }
            
            if options.include_explanations and getattr(question, 'explanation', None):
                feedback = {"text": question.explanation}
                grading["whenRight"] = feedback
                grading["whenWrong"] = feedback
                
            item["item"]["questionItem"]["question"]["grading"] = grading
        
        return item
    
    def _build_fill_blank_item(
        self,
        question: "ExportQuestionFillBlank",
        index: int,
        options: "ExportOptions"
    ) -> Dict[str, Any]:
        """
        Build a fill-in-the-blank question item for Google Forms.
        
        Note: Google Forms API does NOT support correctAnswers for textQuestion types.
        Text questions require manual grading. We use generalFeedback to show the
        correct answer to instructors during grading, and whenWrong feedback for
        students after submission.
        
        Reference: https://developers.google.com/forms/api/reference/rest/v1/forms#Grading
        """
        
        item = {
            "item": {
                "title": question.question,
                "questionItem": {
                    "question": {
                        "required": True,
                        "textQuestion": {
                            "paragraph": False  # Short answer
                        }
                    }
                }
            },
            "location": {"index": index}
        }
        
        # Add grading info if answer key is included
        # IMPORTANT: textQuestion does NOT support correctAnswers or whenRight/whenWrong
        # for auto-grading. Only choiceQuestion types support automatic grading.
        # For text questions, we only set pointValue and generalFeedback.
        # generalFeedback shows the expected answer during manual grading.
        if options.include_answer_key:
            feedback_text = f"Expected answer: {question.correct_answer}"
            
            if options.include_explanations:
                explanation = getattr(question, 'explanation', None)
                distractors = getattr(question, 'distractor_explanations', None)
                
                if explanation:
                    feedback_text += f"\n\nExplanation: {explanation}"
                
                if distractors and isinstance(distractors, dict):
                    feedback_text += "\n\nWhy other options are incorrect:"
                    for opt, reason in distractors.items():
                        feedback_text += f"\n• {opt}: {reason}"
            
            item["item"]["questionItem"]["question"]["grading"] = {
                "pointValue": self.DEFAULT_POINT_VALUE,
                "generalFeedback": {
                    "text": feedback_text
                }
                # NOTE: whenRight/whenWrong CANNOT be used with textQuestion.
                # Google Forms API error: "Correct/incorrect answer feedback can only be set for multiple choice questions."
            }
        
        return item
    
    def _find_correct_option_index(
        self, options: List[str], correct_answer: str
    ) -> int:
        """Find index of correct answer in options list."""
        # Try exact match first
        for idx, opt in enumerate(options):
            if opt == correct_answer:
                return idx
        
        # Try case-insensitive match
        correct_lower = correct_answer.lower().strip()
        for idx, opt in enumerate(options):
            if opt.lower().strip() == correct_lower:
                return idx
        
        # Try letter matching (A, B, C, D)
        if correct_answer.upper() in "ABCD":
            letter_idx = ord(correct_answer.upper()) - ord("A")
            if 0 <= letter_idx < len(options):
                return letter_idx
        
        # Default to first option
        return 0

